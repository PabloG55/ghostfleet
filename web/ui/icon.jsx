function runs(rows) {
  let d = '';
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length;) {
      if (r[x] !== '#') { x++; continue; }
      let e = x;
      while (r[e + 1] === '#') e++;
      d += `M${x} ${y}h${e - x + 1}v1h-${e - x + 1}z`;
      x = e + 1;
    }
  });
  return d;
}
const PATHS = Object.fromEntries(Object.entries(ROWS).map(([k, rows]) => [k, runs(rows)]));
export const ICON_NAMES = Object.keys(ROWS);

// `size` is in CSS pixels and should be a whole multiple of 12 so a sprite pixel never lands
// between two screen pixels; the default is the font's own 12.
export function Icon({ name, size = 12, label, class: cls }) {
  const d = PATHS[name];
  if (!d) return null;
  return (
    <svg class={`px-ico${cls ? ` ${cls}` : ''}`} viewBox="0 0 12 12" width={size} height={size}
         role={label ? 'img' : undefined} aria-label={label} aria-hidden={label ? undefined : 'true'}>
      <path d={d} />
    </svg>
  );
}
